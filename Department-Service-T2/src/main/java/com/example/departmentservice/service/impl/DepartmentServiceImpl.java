package com.example.departmentservice.service.impl;

import com.example.departmentservice.dto.DepartmentDto;
import com.example.departmentservice.entity.Department;
import com.example.departmentservice.exception.DuplicateResourceException;
import com.example.departmentservice.exception.ResourceNotFoundException;
import com.example.departmentservice.repository.DepartmentRepository;
import com.example.departmentservice.service.DepartmentService;
import lombok.AllArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

@Service
@AllArgsConstructor
public class DepartmentServiceImpl implements DepartmentService {

    private final DepartmentRepository departmentRepository;

    @Override
    @Transactional
    public DepartmentDto saveDepartment(DepartmentDto departmentDto) {
        if (departmentRepository.existsByDepartmentCode(departmentDto.getDepartmentCode())) {
            throw new DuplicateResourceException(
                    "Department already exists with code: " + departmentDto.getDepartmentCode());
        }

        // id is always generated by the database; any id sent by the client is ignored
        Department department = new Department(
                null,
                departmentDto.getDepartmentName(),
                departmentDto.getDepartmentDescription(),
                departmentDto.getDepartmentCode()
        );

        return toDto(departmentRepository.save(department));
    }

    @Override
    @Transactional(readOnly = true)
    public DepartmentDto getDepartmentById(Long departmentId) {
        return toDto(findOrThrow(departmentId));
    }

    @Override
    @Transactional(readOnly = true)
    public DepartmentDto getDepartmentByCode(String departmentCode) {
        Department department = departmentRepository.findByDepartmentCode(departmentCode)
                .orElseThrow(() -> new ResourceNotFoundException("Department not found with code: " + departmentCode));
        return toDto(department);
    }

    @Override
    @Transactional(readOnly = true)
    public List<DepartmentDto> getAllDepartments() {
        return departmentRepository.findAll().stream().map(this::toDto).toList();
    }

    @Override
    @Transactional
    public DepartmentDto updateDepartment(Long departmentId, DepartmentDto departmentDto) {
        Department department = findOrThrow(departmentId);

        departmentRepository.findByDepartmentCode(departmentDto.getDepartmentCode())
                .filter(other -> !other.getId().equals(departmentId))
                .ifPresent(other -> {
                    throw new DuplicateResourceException(
                            "Department already exists with code: " + departmentDto.getDepartmentCode());
                });

        department.setDepartmentName(departmentDto.getDepartmentName());
        department.setDepartmentDescription(departmentDto.getDepartmentDescription());
        department.setDepartmentCode(departmentDto.getDepartmentCode());

        return toDto(departmentRepository.save(department));
    }

    @Override
    @Transactional
    public void deleteDepartment(Long departmentId) {
        departmentRepository.delete(findOrThrow(departmentId));
    }

    private Department findOrThrow(Long departmentId) {
        return departmentRepository.findById(departmentId)
                .orElseThrow(() -> new ResourceNotFoundException("Department not found with id: " + departmentId));
    }

    private DepartmentDto toDto(Department department) {
        return new DepartmentDto(
                department.getId(),
                department.getDepartmentName(),
                department.getDepartmentDescription(),
                department.getDepartmentCode()
        );
    }
}
