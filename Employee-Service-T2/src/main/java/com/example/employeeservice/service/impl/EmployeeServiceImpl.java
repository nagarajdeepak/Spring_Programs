package com.example.employeeservice.service.impl;

import com.example.employeeservice.dto.APIResponseDto;
import com.example.employeeservice.dto.DepartmentDto;
import com.example.employeeservice.dto.EmployeeDto;
import com.example.employeeservice.entity.Employee;
import com.example.employeeservice.exception.DuplicateResourceException;
import com.example.employeeservice.exception.ResourceNotFoundException;
import com.example.employeeservice.exception.ServiceUnavailableException;
import com.example.employeeservice.repository.EmployeeRepository;
import com.example.employeeservice.service.EmployeeService;
import lombok.AllArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.web.reactive.function.client.WebClient;
import org.springframework.web.reactive.function.client.WebClientRequestException;
import org.springframework.web.reactive.function.client.WebClientResponseException;

import java.util.List;

@Service
@AllArgsConstructor
public class EmployeeServiceImpl implements EmployeeService {

    private final EmployeeRepository employeeRepository;
    private final WebClient webClient; // base URL configured in EmployeeServiceApplication

    @Override
    public EmployeeDto saveEmployee(EmployeeDto employeeDto) {
        if (employeeRepository.existsByEmail(employeeDto.getEmail())) {
            throw new DuplicateResourceException("Employee already exists with email: " + employeeDto.getEmail());
        }
        // Make sure the department really exists in Department-Service
        fetchDepartment(employeeDto.getDepartmentCode());

        // id is always generated by the database; any id sent by the client is ignored
        Employee employee = new Employee(
                null,
                employeeDto.getFirstName(),
                employeeDto.getLastName(),
                employeeDto.getEmail(),
                employeeDto.getDepartmentCode()
        );

        return toDto(employeeRepository.save(employee));
    }

    @Override
    public APIResponseDto getEmployeeById(Long employeeId) {
        Employee employee = findOrThrow(employeeId);
        DepartmentDto departmentDto = fetchDepartment(employee.getDepartmentCode());
        return new APIResponseDto(toDto(employee), departmentDto);
    }

    @Override
    public List<EmployeeDto> getAllEmployees() {
        return employeeRepository.findAll().stream().map(this::toDto).toList();
    }

    @Override
    public EmployeeDto updateEmployee(Long employeeId, EmployeeDto employeeDto) {
        Employee employee = findOrThrow(employeeId);

        employeeRepository.findByEmail(employeeDto.getEmail())
                .filter(other -> !other.getId().equals(employeeId))
                .ifPresent(other -> {
                    throw new DuplicateResourceException(
                            "Employee already exists with email: " + employeeDto.getEmail());
                });

        fetchDepartment(employeeDto.getDepartmentCode());

        employee.setFirstName(employeeDto.getFirstName());
        employee.setLastName(employeeDto.getLastName());
        employee.setEmail(employeeDto.getEmail());
        employee.setDepartmentCode(employeeDto.getDepartmentCode());

        return toDto(employeeRepository.save(employee));
    }

    @Override
    public void deleteEmployee(Long employeeId) {
        employeeRepository.delete(findOrThrow(employeeId));
    }

    private Employee findOrThrow(Long employeeId) {
        return employeeRepository.findById(employeeId)
                .orElseThrow(() -> new ResourceNotFoundException("Employee not found with id: " + employeeId));
    }

    /** Calls Department-Service and translates failures into clean API errors. */
    private DepartmentDto fetchDepartment(String departmentCode) {
        try {
            return webClient.get()
                    .uri("/api/departments/code/{code}", departmentCode)
                    .retrieve()
                    .bodyToMono(DepartmentDto.class)
                    .block();
        } catch (WebClientResponseException.NotFound ex) {
            throw new ResourceNotFoundException("Department not found with code: " + departmentCode);
        } catch (WebClientResponseException ex) {
            throw new ServiceUnavailableException(
                    "Department-Service returned an error (HTTP " + ex.getStatusCode().value() + ")");
        } catch (WebClientRequestException ex) {
            throw new ServiceUnavailableException(
                    "Department-Service is not reachable. Make sure it is running (default port 8081).");
        }
    }

    private EmployeeDto toDto(Employee employee) {
        return new EmployeeDto(
                employee.getId(),
                employee.getFirstName(),
                employee.getLastName(),
                employee.getEmail(),
                employee.getDepartmentCode()
        );
    }
}
